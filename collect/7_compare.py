"""Compare the collected values with the released table, column by column.
Exact comparison for text and flags; numbers that move with time (downloads, stars, forks, hits) are
compared within a tolerance. Writes compare_report.md next to the scripts (repository root: tests/)."""
import csv, os, sys
from collections import Counter
from common import WORK
HERE = os.path.dirname(os.path.abspath(__file__))
REL = os.path.join(HERE, '..', 'data', 'icon_sets_v3.csv')
COL = os.path.join(WORK, 'collected.csv')
OUT = os.path.join(HERE, '..', 'tests', 'collection_compare.md')
rel = {r['set_id']: r for r in csv.DictReader(open(REL, encoding='utf-8'))}
col = {r['set_id']: r for r in csv.DictReader(open(COL, encoding='utf-8'))}
header = list(csv.DictReader(open(REL, encoding='utf-8')).fieldnames)
MOVING = {'npm_downloads_30d', 'npm_downloads_prev30d', 'npm_downloads_365d', 'iconify_downloads_30d', 'iconify_downloads_365d',
          'npm_jsdelivr_hits_30d', 'gh_stars', 'gh_forks', 'repo_commits_365d', 'pkg_commits_365d', 'repo_authors_365d',
          'pkg_authors_365d', 'repo_days_since_last_commit', 'repo_age_years', 'repo_top_author_share_365d', 'stable_releases_730d',
          'release_gap_median_days', 'npm_versions_total', 'npm_unpacked_size_bytes', 'repo_files_total', 'repo_svg_files',
          'repo_semver_tags', 'repo_commits_total', 'pkg_commits_total', 'repo_authors_total', 'pkg_authors_365d'}

def close(a, b, rel_tol=0.10):
    try:
        x, y = float(a), float(b)
    except ValueError:
        return False
    return abs(x - y) <= max(1e-9, rel_tol * max(abs(x), abs(y)))

stats = {}
examples = {}
for sid, r in rel.items():
    c = col.get(sid)
    if c is None: continue
    for k in header:
        if k in ('id', 'checked_on'): continue
        a, b = r.get(k, ''), c.get(k, '')
        if not b and not a: continue
        s = stats.setdefault(k, Counter())
        if not b:
            s['not collected here'] += 1; continue
        if not a:
            s['only collected'] += 1; continue
        if a == b or (k in MOVING and close(a, b)):
            s['match'] += 1
        else:
            s['differs'] += 1
            examples.setdefault(k, []).append(f'{sid}: release={a[:60]!r} collected={b[:60]!r}')
lines = ['# Collection comparison (generated by collect/7_compare.py)', '',
         f'Release: `data/icon_sets_v3.csv`. Collected: `collect/work/collected.csv` (collection day 2026-11-16, UTC cut-off 23:59:59).',
         'Numbers that change with time (downloads, stars, forks, hits, and commit counts that a later date would change) match within 10 %.',
         '', '| column | match | differs | only in release | only collected |', '|---|---:|---:|---:|---:|']
totals = Counter()
for k in header:
    if k not in stats: continue
    s = stats[k]
    totals.update(s)
    lines.append(f'| {k} | {s["match"]} | {s["differs"]} | {s["not collected here"]} | {s["only collected"]} |')
lines += ['', f'Totals over compared cells: match {totals["match"]}, differs {totals["differs"]}.', '', '## Examples of differences', '']
for k, ex in examples.items():
    lines.append(f'**{k}** ({len(ex)})')
    lines += [f'- {e}' for e in ex[:4]]
    lines.append('')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(f'compared {len(stats)} columns; match {totals["match"]}, differs {totals["differs"]}; report: {OUT}')
